import { createHmac, randomBytes, randomUUID, timingSafeEqual } from 'node:crypto';
import { createWriteStream } from 'node:fs';
import { mkdir, open, rename, rm, stat, truncate, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { pipeline } from 'node:stream/promises';
import { contentDisposition, exactLength, type StorageDriver } from './storage.js';

/**
 * Stores files in a folder on this computer instead of Cloudflare R2.
 *
 * Downloads and previews work like R2's presigned URLs: the server hands out a
 * short-lived link to /api/blobs/file?...&sig=... that is signed with a secret
 * (HMAC). Only links created by the server, and not yet expired, are served.
 */

// Storage keys are always generated by the server in this exact shape.
// Anything else is rejected, so a key can never point outside the storage folder.
const KEY_PATTERN = /^users\/[a-f0-9]{24}\/[0-9a-f-]{36}$/;

// A new random secret each time the server starts. Links live for minutes, so
// links from before a restart simply stop working, which is fine.
const signingSecret = randomBytes(32);

export const BLOB_ROUTE = '/api/blobs/file';

/** Turns a storage key into an absolute path inside rootDir (or throws). */
export function keyToPath(rootDir: string, key: string): string {
  if (!KEY_PATTERN.test(key)) throw new Error('Invalid storage key');
  const root = resolve(rootDir);
  const full = resolve(root, ...key.split('/'));
  if (!full.startsWith(root + sep)) throw new Error('Invalid storage key');
  return full;
}

export interface BlobLinkParams {
  key: string;
  exp: number; // unix seconds
  type: string; // Content-Type to send
  disp: string; // Content-Disposition to send
}

function sign(p: BlobLinkParams): string {
  return createHmac('sha256', signingSecret)
    .update(`${p.key}\n${p.exp}\n${p.type}\n${p.disp}`)
    .digest('base64url');
}

/** Checks a link's signature and expiry. Returns the params, or null if invalid. */
export function verifyBlobLink(query: Record<string, string | undefined>): BlobLinkParams | null {
  const { key, exp, type, disp, sig } = query;
  if (!key || !exp || !type || !disp || !sig) return null;
  const params = { key, exp: Number(exp), type, disp };
  if (!Number.isInteger(params.exp) || params.exp < Date.now() / 1000) return null;

  const expected = Buffer.from(sign(params));
  const given = Buffer.from(sig);
  if (expected.length !== given.length || !timingSafeEqual(expected, given)) return null;
  return params;
}

export function createLocalDriver(rootDir: string): StorageDriver {
  return {
    async putObject(key, body) {
      const path = keyToPath(rootDir, key);
      await mkdir(dirname(path), { recursive: true });
      // Write to a temporary file first and rename at the end, so a failed or
      // cancelled upload never leaves a half-written file under the real name.
      const tmp = `${path}.${randomUUID()}.uploading`;
      try {
        await pipeline(body, createWriteStream(tmp));
        await rename(tmp, path);
      } catch (err) {
        await rm(tmp, { force: true });
        throw err;
      }
    },

    async deleteObjects(keys) {
      for (const key of keys) {
        await rm(keyToPath(rootDir, key), { force: true }); // force: no error if already gone
      }
    },

    async getSignedDownloadUrl(key, options) {
      keyToPath(rootDir, key); // validate
      const params: BlobLinkParams = {
        key,
        exp: Math.floor(Date.now() / 1000) + options.expiresInSeconds,
        type: options.contentType,
        disp: contentDisposition(options.filename, options.inline),
      };
      const query = new URLSearchParams({ ...params, exp: String(params.exp), sig: sign(params) });
      return `${BLOB_ROUTE}?${query}`;
    },

    async readObjectStart(key, maxBytes) {
      const handle = await open(keyToPath(rootDir, key), 'r');
      try {
        const buffer = Buffer.alloc(maxBytes);
        const { bytesRead } = await handle.read(buffer, 0, maxBytes, 0);
        return new Uint8Array(buffer.subarray(0, bytesRead));
      } finally {
        await handle.close();
      }
    },

    // Resumable uploads: parts are written into "<file>.partial" at their
    // byte offset; completing renames it to the real name.
    async startMultipart(key) {
      const path = keyToPath(rootDir, key);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(`${path}.partial`, '');
      return null;
    },

    async putPart(key, _multipartId, _index, offset, size, body) {
      const partial = `${keyToPath(rootDir, key)}.partial`;
      const info = await stat(partial).catch(() => null);
      if (!info) throw new Error('Upload data not found on disk');
      if (info.size < offset) throw new Error('Upload data on disk is shorter than expected');
      // Drop anything after `offset` (e.g. half a part from a dropped connection).
      await truncate(partial, offset);
      try {
        await pipeline(body, exactLength(size), createWriteStream(partial, { flags: 'r+', start: offset }));
      } catch (err) {
        await truncate(partial, offset).catch(() => undefined); // undo the incomplete part
        throw err;
      }
    },

    async completeMultipart(key) {
      const path = keyToPath(rootDir, key);
      await rename(`${path}.partial`, path);
    },

    async abortMultipart(key) {
      await rm(`${keyToPath(rootDir, key)}.partial`, { force: true });
    },
  };
}
